# pandas와 numpy는 데이터 분석에 필수적인 라이브러리입니다.
# pandas는 표(데이터 프레임), numpy는 행렬(배열) 계산에 주로 사용됩니다.
import pandas as pd
import numpy as np
# scikit-learn은 머신러닝을 위한 다양한 도구와 예제 데이터를 제공하는 라이브러리입니다.
# 여기서는 그 안에 포함된 붓꽃(iris) 데이터를 불러오기 위해 load_iris 함수를 사용합니다.
from sklearn.datasets import load_iris

# 이 파일이 직접 실행될 때만 아래 코드가 동작합니다.
if __name__ == '__main__':
    # load_iris() 함수를 호출하여 붓꽃 데이터를 불러옵니다.
    # 이 데이터 안에는 꽃의 특징 데이터(data), 품종 정보(target), 품종 이름(target_names), 특징 이름(feature_names) 등이 들어있습니다.
    iris = load_iris()
    
    # 붓꽃 데이터에서 실제 측정 데이터(꽃받침 길이/너비, 꽃잎 길이/너비) 부분만 가져와 X 라는 변수에 저장합니다.
    # X는 보통 머신러닝에서 '입력 데이터' 또는 '특징(feature) 데이터'를 의미하는 변수명으로 많이 사용됩니다.
    X = iris.data
    
    # X.T는 X의 행과 열을 바꾼 '전치 행렬'을 의미합니다.
    # '@' 연산자는 행렬 곱셈을 수행합니다.
    # 즉, 'X의 전치 행렬'과 '원본 X 행렬'을 곱하는 과정입니다.
    # 이 계산은 데이터의 '공분산 행렬'과 밀접한 관련이 있으며,
    # 각 특징(꽃받침 길이, 꽃잎 너비 등)들이 서로 어떤 관계를 맺고 있는지를 압축적으로 보여줍니다.
    # 주성분 분석(PCA)과 같은 차원 축소 기법의 핵심 계산 단계 중 하나입니다.
    Cov = X.T @ X
    
    # 계산된 행렬(Cov)을 출력합니다.
    print(Cov)
